type LanguageContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: MessageKey) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<AppLanguage>("zh-CN");

  useEffect(() => {
    let disposed = false;
    let loaded = false;
    const load = async () => {
      if (loaded) return;
      try {
        const response = await productFetch("/api/settings");
        if (!response.ok) return;
        const payload = await response.json() as { app_language?: AppLanguage };
        if (!disposed && (payload.app_language === "zh-CN" || payload.app_language === "en")) {
          setLanguage(payload.app_language);
          loaded = true;
        }
      } catch {
        // Product API may still be starting; the default Chinese UI remains usable meanwhile.
      }
    };
    void load();
    const timer = window.setInterval(() => void load(), 2000);
    return () => {
      disposed = true;
      window.clearInterval(timer);
    };
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (key) => (language === "zh-CN" ? zh : en)[key],
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}
